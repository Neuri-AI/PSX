"""Compile literal PSX calls inside @component without a separate build step.

This operates on the component's source at declaration time, not caller frames.
Only Python's AST compiler is used; no dynamically sourced expressions are run.
"""

from __future__ import annotations

import ast
import inspect
import textwrap
from types import CodeType, FunctionType
from typing import Callable

from psx.markup.compile import compile_template
from psx.markup.transform import transform_source

_HELPERS = {
    "_psx_expr_element": "element",
    "_psx_expr_fragment": "fragment",
    "_psx_expr_lexical": "lexical",
    "_psx_expr_member": "member",
    "_psx_expr_index": "index",
    "_psx_expr_conditional": "conditional",
    "_psx_expr_compute_styles": "compute_expressive_markup_styles",
    "_psx_expr_map_children": "map_children",
}


class _RenameGenerated(ast.NodeTransformer):
    def __init__(self, names: dict[str, str]) -> None:
        self.names = names

    def visit_Name(self, node: ast.Name) -> ast.AST:
        if node.id in self.names:
            node.id = self.names[node.id]
        return node


def compile_component(function: Callable[..., object]) -> Callable[..., object]:
    """Bind PSX identifiers to the component's Python lexical names.

    The transformed function uses code generated by ast/compile; runtime
    interpolation never reads a frame, evaluates text, or invokes a compiler.
    Non-literal PSX calls and explicit-scope calls retain their current API.
    """
    # velto build transforms every project module before PyInstaller analysis.
    # Frozen components already contain lexical bindings in their code objects;
    # inspecting their original source would both fail and require shipping .py.
    if function.__globals__.get("__psx_build_precompiled__") is True:
        return function

    try:
        lines, start_line = inspect.getsourcelines(function)
    except (OSError, TypeError):
        if "psx" in function.__code__.co_names:
            raise TypeError(
                f"Cannot locate source for PSX component {function.__qualname__}; "
                "literal PSX markup in @component requires a readable Python file."
            ) from None
        return function

    source = textwrap.dedent("".join(lines))
    filename = inspect.getsourcefile(function) or function.__code__.co_filename
    result = transform_source(source, filename=filename)
    if not result.transformed_calls:
        return function

    # Executing a separately compiled module would run arbitrary module code.
    # Instead, take ONLY the code object produced for the component definition.
    module = ast.parse(result.source, filename=filename)
    definitions = [
        node for node in module.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        and node.name == function.__name__
    ]
    if len(definitions) != 1:
        raise TypeError(f"Cannot identify transformed component {function.__qualname__}.")
    definition = definitions[0]
    definition.decorator_list = []

    templates: dict[str, tuple[str, str]] = {}
    for node in module.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target, value = node.targets[0], node.value
        if not isinstance(target, ast.Name) or not target.id.startswith("_psx_template_"):
            continue
        if not isinstance(value, ast.Call) or not value.args:
            continue
        template = value.args[0]
        if not isinstance(template, ast.Constant) or not isinstance(template.value, str):
            continue
        template_filename = filename
        for keyword in value.keywords:
            if keyword.arg == "filename" and isinstance(keyword.value, ast.Constant):
                template_filename = keyword.value.value
        templates[target.id] = (template.value, template_filename)

    prefix = f"_psx_component_{id(function):x}_"
    names = {key: prefix + key for key in templates}
    if any(entry.template_name.startswith("_psx_expressive_") for entry in result.source_map.entries):
        names.update({key: prefix + key for key in _HELPERS})
    _RenameGenerated(names).visit(definition)

    # Python closures cannot be reconstructed from a separately compiled
    # top-level definition without rewriting the containing lexical scope.
    if function.__code__.co_freevars:
        raise TypeError(
            f"PSX component {function.__qualname__} closes over outer variables; "
            "automatic lexical compilation of nested closures is not supported."
        )

    ast.increment_lineno(definition, start_line - 1)
    generated = ast.Module(body=[definition], type_ignores=[])
    ast.fix_missing_locations(generated)
    module_code = compile(generated, filename, "exec")
    candidate = next(
        (value for value in module_code.co_consts
         if isinstance(value, CodeType) and value.co_name == function.__name__),
        None,
    )
    if candidate is None or candidate.co_freevars:
        raise TypeError(f"Unable to compile lexical PSX component {function.__qualname__}.")

    globals_dict = function.__globals__
    for key, (markup, template_filename) in templates.items():
        globals_dict[names[key]] = compile_template(markup, filename=template_filename)
    if any(key in names for key in _HELPERS):
        from psx.markup import expressive_runtime

        for name, attribute in _HELPERS.items():
            globals_dict[names[name]] = getattr(expressive_runtime, attribute)

    compiled = FunctionType(
        candidate, globals_dict, function.__name__, function.__defaults__,
    )
    compiled.__kwdefaults__ = function.__kwdefaults__
    compiled.__annotations__ = function.__annotations__
    compiled.__dict__.update(function.__dict__)
    compiled.__module__ = function.__module__
    compiled.__qualname__ = function.__qualname__
    compiled.__doc__ = function.__doc__
    return compiled
